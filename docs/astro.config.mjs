import starlight from '@astrojs/starlight';
import { defineConfig } from 'astro/config';
import starlightOpenAPI, { openAPISidebarGroups } from 'starlight-openapi';

/**
 * The documentation site.
 *
 * It lives in this repository rather than its own so a change to the app and the
 * change to its documentation land in the same commit — the only thing that
 * actually keeps the two in step.
 *
 * Published to GitHub Pages by `.github/workflows/docs.yml`. `base` has to match
 * the repository name: Pages serves the site from a sub-path, and every internal
 * link is built from it.
 */
export default defineConfig({
	site: 'https://cedhuf.github.io',
	base: '/llooma',
	integrations: [
		starlight({
			title: 'Llooma',
			description: 'Documentation for Llooma, a (less) minimal LLM chat app.',
			logo: { src: './src/assets/logo-mark.png', alt: 'Llooma' },
			favicon: '/favicon.png',
			social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/cedhuf/llooma' }],
			editLink: {
				baseUrl: 'https://github.com/cedhuf/llooma/edit/main/docs/'
			},
			// English is the base, French is a translation: any page without a French
			// version falls back to English rather than 404ing — the same contract as
			// the app's own `typesafe-i18n` setup, so a half-translated site is fine.
			defaultLocale: 'root',
			locales: {
				root: { label: 'English', lang: 'en' },
				fr: { label: 'Français', lang: 'fr' }
			},
			plugins: [
				starlightOpenAPI([
					{
						base: 'reference/api',
						label: 'HTTP API',
						schema: './openapi.yaml'
					}
				])
			],
			// Autogenerated groups are declared as a label with an `autogenerate` entry
			// inside `items` — the shorthand that put `autogenerate` next to `label`
			// was removed in Starlight 0.39. Page order within a group comes from each
			// page's `sidebar.order` frontmatter.
			sidebar: [
				{
					label: 'Start here',
					translations: { fr: 'Commencer' },
					items: [{ autogenerate: { directory: 'guides' } }]
				},
				{
					label: 'Features',
					translations: { fr: 'Fonctionnalités' },
					items: [{ autogenerate: { directory: 'features' } }]
				},
				{
					label: 'Reference',
					translations: { fr: 'Référence' },
					items: [{ autogenerate: { directory: 'reference' } }]
				},
				...openAPISidebarGroups,
				{
					label: 'Development',
					translations: { fr: 'Développement' },
					items: [{ autogenerate: { directory: 'development' } }]
				}
			]
		})
	]
});
