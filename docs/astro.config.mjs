import starlight from '@astrojs/starlight';
import { defineConfig } from 'astro/config';
import starlightOpenAPI, { openAPISidebarGroups } from 'starlight-openapi';

/**
 * The documentation site.
 *
 * It lives in this repository rather than its own so a change to the app and the
 * change to its documentation land in the same commit, the only thing that
 * actually keeps the two in step.
 *
 * Published to GitHub Pages by `.github/workflows/docs.yml`, served at the apex
 * of llooma.eu. The custom domain is what lets `base` stay at the root: without
 * it Pages serves the site from a sub-path and every internal link carries the
 * repository name.
 */
export default defineConfig({
	site: 'https://llooma.eu',
	// The persona store page reads the app's glyph table directly, which lives
	// outside this project. One table drawn by both, rather than a copy here that
	// would be right on the day it was written.
	vite: { server: { fs: { allow: ['..'] } } },
	integrations: [
		starlight({
			title: 'Llooma',
			description: 'Documentation for Llooma, a (less) minimal LLM chat app.',
			// The mark is black ink on transparency, so it vanishes on a dark
			// background; `dark` swaps in the inverted copy, the same pairing the
			// README does with `<picture>`.
			logo: {
				light: './src/assets/logo-mark.png',
				dark: './src/assets/logo-mark-dark.png',
				alt: 'Llooma'
			},
			favicon: '/favicon.png',
			social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/cedhuf/llooma' }],
			editLink: {
				baseUrl: 'https://github.com/cedhuf/llooma/edit/main/docs/'
			},
			customCss: ['./src/styles/custom.css'],
			// English only. The app's interface is translated, its documentation is
			// not: a second copy of every page is a standing maintenance cost, and a
			// half-translated site tells readers less than a complete English one.
			plugins: [
				starlightOpenAPI([
					{
						base: 'reference/api',
						label: 'HTTP API',
						schema: './openapi.yaml'
					}
				])
			],
			// Autogenerated groups are declared as a label with an `autogenerate` entry
			// inside `items`. The shorthand that put `autogenerate` next to `label`
			// was removed in Starlight 0.39. Page order within a group comes from each
			// page's `sidebar.order` frontmatter.
			sidebar: [
				{
					label: 'Start here',
					items: [{ autogenerate: { directory: 'guides' } }]
				},
				{
					label: 'Features',
					items: [{ autogenerate: { directory: 'features' } }]
				},
				{
					label: 'Reference',
					items: [{ autogenerate: { directory: 'reference' } }]
				},
				...openAPISidebarGroups,
				{
					label: 'Development',
					items: [{ autogenerate: { directory: 'development' } }]
				},
				// Loose pages rather than a directory, so they need explicit entries: the
				// autogenerated groups above only pick up whole directories, and the
				// changelog is not content at all but a page built from the GitHub API.
				{
					label: 'Project',
					items: [
						{ label: 'Persona store', link: '/personas/' },
						{ label: 'Roadmap', link: '/roadmap/' },
						{ label: 'Changelog', link: '/changelog/' },
						{ label: 'Changes from Hollama', link: '/changes-from-hollama/' }
					]
				}
			]
		})
	]
});
